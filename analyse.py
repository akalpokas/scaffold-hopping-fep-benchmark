import json
import argparse
from pathlib import Path
from pipeline.schemas import RBFEEdge, RHFEEdge, AHFENode

from analysis.ddG import ddGAnalyzer
from analysis.energy_traj import EnergyTrajAnalyzer
from analysis.convergence import ConvergenceAnalyzer

# Registry of available analyses
AVAILABLE_MODULES = {
    "energy_traj": EnergyTrajAnalyzer(),
    "ddG": ddGAnalyzer(),
    "convergence": ConvergenceAnalyzer(),
}


def parse_config(edge_dict: dict):
    """Dynamically parses the dictionary into the correct Pydantic schema."""
    if "protein_paths" in edge_dict:
        return RBFEEdge(**edge_dict)
    elif "ligand_b_paths" in edge_dict:
        return RHFEEdge(**edge_dict)
    else:
        return AHFENode(**edge_dict)


def determine_legs(config, requested_leg: str) -> list[str]:
    """Determines valid legs based on the system type (RBFE vs HFE)."""
    if isinstance(config, RBFEEdge):
        valid_legs = ["free", "bound"]
    elif isinstance(config, (RHFEEdge, AHFENode)):
        if isinstance(config, AHFENode):
            valid_legs = ["solvent"]  # AHFE nodes only have solvent leg
        else:
            valid_legs = ["solvent", "vacuum"]  # RHFE edges have both legs

    if requested_leg.lower() == "all":
        return valid_legs
    elif requested_leg.lower() in valid_legs:
        return [requested_leg.lower()]
    return []


def get_run_folder_name(
    config, leg: str, protocol: str, rep: int, k: str, de: str, ghost_mods: bool
) -> str:
    """Reconstructs the exact folder name generated by edge_runner.py."""
    bond_alchemy = False
    notes = str(config.metadata.get("notes", "")).lower()

    if isinstance(config, (RBFEEdge, RHFEEdge)):
        if "bond annihilation" in notes or "bond creation" in notes:
            bond_alchemy = True

    mods_prefix = "ghost_mods_" if ghost_mods else ""

    if bond_alchemy:
        return (
            f"{leg}_k_{k}_{mods_prefix}de_{de}_{protocol}_2026_07_03_devel_repl_{rep}"
        )
    else:
        return f"{leg}_{mods_prefix}{protocol}_2026_07_03_devel_repl_{rep}"


def run_analysis(
    network_path: Path,
    active_modules: list,
    protocol: str,
    k: str,
    de: str,
    ghost_mods: bool,
    requested_leg: str,
    replicate: int = None,
    specific_edge: str = None,
):
    with open(network_path, "r") as f:
        edges_data = json.load(f)

    if specific_edge:
        edges_data = [e for e in edges_data if e.get("edge_id") == specific_edge]
        if not edges_data:
            print(f"Error: ID '{specific_edge}' not found in network.")
            return

    print(f"Running analyses: {[m.name for m in active_modules]}\n")

    replicates_to_run = [replicate] if replicate is not None else [1, 2, 3]

    for edge_dict in edges_data:
        try:
            config = parse_config(edge_dict)
            edge_id = config.id

            # Centralized analysis output folder
            out_dir = config.output_dir / "analysis"
            out_dir.mkdir(parents=True, exist_ok=True)

            print(f"=== Analyzing: {edge_id} ===")

            legs_to_run = determine_legs(config, requested_leg)
            if not legs_to_run:
                print(
                    f"    [!] Skipping: Requested leg '{requested_leg}' invalid for this system."
                )
                continue

            # 1 & 2: Replicate and Leg Level
            for leg in legs_to_run:
                for rep in replicates_to_run:
                    # Dynamically predict the folder name
                    run_folder = get_run_folder_name(
                        config, leg, protocol, rep, k, de, ghost_mods
                    )
                    run_dir = config.output_dir / run_folder

                    if run_dir.exists():
                        # Pass the directory to every active module
                        for module in active_modules:
                            module.analyze_replicate(
                                edge_id, run_dir, out_dir, leg, rep
                            )
                    else:
                        print(f"    [!] Missing run directory: {run_folder}")

                # After all replicates for this leg are done, trigger aggregation
                for module in active_modules:
                    module.aggregate_leg(edge_id, out_dir, leg)

            # 3: Edge/Node Level (Cross-leg comparison)
            for module in active_modules:
                module.compare_edge(edge_id, out_dir)

            print("")  # Formatting newline
        except Exception as e:
            print(
                f"    [!] Error processing {edge_dict.get('edge_id', 'Unknown ID')}: {e}"
            )
            continue


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Network-wide analysis script for Alchemical Free Energy benchmarks."
    )

    parser.add_argument("--network", required=True, type=Path)
    parser.add_argument("--protocol", required=True, type=str)

    parser.add_argument(
        "--modules",
        nargs="+",
        choices=AVAILABLE_MODULES.keys(),
        default=["energy_traj"],
        help="List of analysis modules to run (e.g., --modules energy_traj convergence)",
    )

    parser.add_argument(
        "--edge-id",
        default=None,
        type=str,
        help="Optional: Analyze only a single edge or node",
    )

    parser.add_argument(
        "--k", default="125", type=str, help="Soft Morse bond strength. Default is 125."
    )
    parser.add_argument(
        "--de",
        default="50",
        type=str,
        help="Soft Morse dissociation energy. Default is 50.",
    )

    parser.add_argument(
        "--leg_name",
        required=False,
        default="all",
        type=str,
        choices=["free", "bound", "solvent", "vacuum", "all"],
        help="Leg to analyze: 'free', 'bound', 'solvent', 'vacuum', or 'all' (default)",
    )

    parser.add_argument(
        "--replicate",
        required=False,
        type=int,
        help="Optional: Specific replicate number to run",
    )

    parser.add_argument(
        "--ghost_modifications",
        action="store_true",
        help="Whether ghost modifications were applied during the run.",
    )

    args = parser.parse_args()
    active_modules = [AVAILABLE_MODULES[m] for m in args.modules]

    run_analysis(
        network_path=args.network,
        active_modules=active_modules,
        protocol=args.protocol,
        k=args.k,
        de=args.de,
        ghost_mods=args.ghost_modifications,
        requested_leg=args.leg_name,
        replicate=args.replicate,
        specific_edge=args.edge_id,
    )
